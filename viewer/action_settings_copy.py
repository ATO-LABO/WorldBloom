def describe(verb, world):
    result = SUMMARIES.get(verb)
    if result is None:
        return verb, '主な条件の説明は未設定です。設定元で確認してください。', '変化の説明は未設定です。設定元で確認してください。'
    name, conditions, effect = result
    if verb == 'buy':
        if world.mechanics_enabled('budgeted_purchases'):
            conditions = '販売場所と品物の購入条件を満たし、設定価格の支払いに必要な資産を持つ。'
            effect = '設定された価格を支払い、品物を1個得る。'
        else:
            conditions = '販売場所と品物の購入条件を満たす。金銭・資産が無効なので、資産額は確認しない。'
            effect = '支払い資産を消費せず、品物を1個得る。販売場所・販売可否などの条件は残る。'
    if verb == 'rest':
        effect = ('設定された回復量で体力を回復する。' if world.mechanics_enabled('stamina_management')
                  else '体力管理が無効なので、体力の消費・回復は行わない。')
    return name, conditions, effect
